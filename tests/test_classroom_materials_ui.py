import classroom as rooms
import classroom_materials as materials
from test_browser_components import browser_page
from test_coach_chess_ui import coach_server
from playwright.sync_api import expect


def test_teacher_authors_exam_student_trains_submits_and_keeps_notebook(browser_page,coach_server,tmp_path,monkeypatch):
    expect.set_options(timeout=30000)
    monkeypatch.setenv('COACH_CLASSROOM_DB',str(tmp_path/'classrooms.sqlite3'))
    owner=rooms.bootstrap_owner('creator','password-creator-123')
    invitation=rooms.issue_professor_key(owner,'Teacher')
    teacher=rooms.enter_professor('teacher','password-teacher-123',invitation)
    student=rooms.students(teacher)[0]
    player=rooms.register_user('learner','password-learner-123')
    pupil=rooms.join_room(player,student['access_key'])
    tactic=materials.save_material(teacher,student['id'],'Mate abafado da aula','tactic',dict(fen='6rk/6pp/8/4N3/8/8/8/6K1 w - - 0 1',solution=['e5f7']))
    materials.save_material(teacher,student['id'],'Modelo comentado','game',dict(pgn='1. e4 {Controle o centro} e5 *',side='white'))
    page=browser_page;page.set_viewport_size({'width':1440,'height':1100});page.goto(coach_server)
    page.get_by_role('radio',name='Professor',exact=True).click()
    page.get_by_role('textbox',name='Usuário',exact=True).fill('teacher')
    page.get_by_role('textbox',name='Senha',exact=True).fill('password-teacher-123')
    page.get_by_role('textbox',name='Chave especial do Professor (obrigatória)',exact=True).fill(invitation)
    page.get_by_role('button',name='Entrar',exact=True).click()
    page.get_by_role('tab',name='Treino e provas',exact=True).click()
    page.locator('.tool[data-kind=exam]').get_by_role('button',name='Adicionar',exact=False).click()
    page.get_by_role('textbox',name='Nome da atividade',exact=True).fill('Prova da aula')
    page.get_by_role('spinbutton',name='Quantidade de perguntas',exact=True).fill('3')
    page.get_by_role('spinbutton',name='Quantidade de perguntas',exact=True).press('Tab')
    expect(page.get_by_role('textbox',name='Enunciado',exact=True)).to_have_count(3)
    page.get_by_text('Fechada',exact=True).first.click()
    page.get_by_role('textbox',name='Enunciado',exact=True).nth(0).fill('Quem joga em L?')
    page.get_by_role('textbox',name='Alternativa A',exact=True).fill('Bispo')
    page.get_by_role('textbox',name='Alternativa B',exact=True).fill('Cavalo')
    page.get_by_text('B',exact=True).click()
    page.get_by_role('textbox',name='Enunciado',exact=True).nth(1).fill('Peça mais valiosa?')
    page.get_by_text('Gabarito para correção automática',exact=True).first.click()
    page.get_by_role('textbox',name='Gabarito / respostas aceitas (opcional)',exact=True).nth(0).fill('Rei | O rei')
    page.get_by_role('textbox',name='Enunciado',exact=True).nth(2).fill('Explique seu plano.')
    page.get_by_role('textbox',name='Enunciado',exact=True).nth(2).press('Tab')
    page.get_by_role('button',name='Salvar atividade',exact=False).click()
    expect(page.get_by_text('Atividade salva.',exact=True)).to_be_visible()
    page.get_by_role('button',name='Fechar edição',exact=True).click()
    page.get_by_role('button',name='Disponibilizar trilha ao aluno',exact=True).click()
    expect(page.get_by_text('Trilha disponível · 1 atividades. O progresso anterior foi preservado.',exact=True)).to_be_visible()
    page.screenshot(path='tests/artifacts/teacher-exam-editor.png',full_page=True)
    context=page.context.browser.new_context(viewport={'width':1440,'height':1100})
    learner=context.new_page()
    try:
        learner.goto(coach_server)
        learner.get_by_role('textbox',name='Usuário',exact=True).fill('learner')
        learner.get_by_role('textbox',name='Senha',exact=True).fill('password-learner-123')
        learner.get_by_role('button',name='Entrar',exact=True).click()
        learner.get_by_role('button',name='Abrir sala do Professor',exact=True).click()
        learner.get_by_role('tab',name='Treino e provas',exact=True).click()
        expect(learner.get_by_role('heading',name='Prova da aula',exact=True)).to_be_visible()
        learner.screenshot(path='tests/artifacts/student-exam.png',full_page=True)
        learner.get_by_text('Cavalo',exact=True).click()
        learner.get_by_role('textbox',name='Sua resposta',exact=True).nth(0).fill('O REI')
        learner.get_by_role('textbox',name='Sua resposta',exact=True).nth(1).fill('Controlar o centro e desenvolver.')
        learner.get_by_role('button',name='Entregar prova',exact=True).click()
        expect(learner.get_by_text('Prova enviada · 2/3 pontos · Nota parcial',exact=True)).to_be_visible()
        assert all('answer' not in q for q in materials.list_materials(pupil)[0]['payload']['questions'])
        page.get_by_role('tab',name='Materiais e correções',exact=True).click()
        page.get_by_text('Prova · Prova da aula · Disponível',exact=True).click()
        page.get_by_role('spinbutton',name='Nota da pergunta 3',exact=True).fill('1')
        page.get_by_role('textbox',name='Comentário do Professor 3',exact=True).fill('Bom plano.')
        page.get_by_role('button',name='Salvar correção',exact=True).click()
        expect(page.get_by_text('Correção salva.',exact=True)).to_be_visible()
        assert materials.list_materials(pupil)[0]['result']['pending']==0
        learner.get_by_role('button',name='Outros materiais',exact=True).click()
        expect(learner.get_by_role('heading',name=__import__('re').compile('^(Modelo comentado|Mate abafado da aula)$'))).to_be_visible()
        if not learner.get_by_role('heading',name='Mate abafado da aula',exact=True).is_visible():
            learner.get_by_role('combobox',name='Material da aula',exact=True).click()
            learner.get_by_role('option',name='Tático · Mate abafado da aula',exact=True).click()
        expect(learner.get_by_role('heading',name='Mate abafado da aula',exact=True)).to_be_visible()
        learner.locator('[data-square=e5]').click()
        expect(learner.locator('[data-square=e5]')).to_have_class(__import__('re').compile(r'.*selected.*'))
        learner.locator('[data-square=f7]').click()
        expect(learner.get_by_text('Treino concluído!',exact=True)).to_be_visible()
        assert next(m for m in materials.list_materials(teacher,student['id']) if m['id']==tactic)['progress']['completed']==1
        learner.get_by_role('combobox',name='Material da aula',exact=True).click()
        learner.get_by_role('option',name='Partida estudada · Modelo comentado',exact=True).click()
        expect(learner.get_by_role('slider',name='Percorrer lances',exact=False)).to_be_visible()
        learner.get_by_role('slider',name='Percorrer lances',exact=False).focus();learner.keyboard.press('ArrowRight')
        expect(learner.get_by_text('Controle o centro',exact=True)).to_be_visible()
        learner.get_by_role('button',name='Abrir esta partida na análise',exact=False).click()
        learner.get_by_role('tab',name='Caderno',exact=True).click()
        learner.get_by_role('textbox',name='Pontos importantes do estudo',exact=True).fill('Desenvolver antes de atacar.')
        learner.get_by_role('button',name='Salvar anotação',exact=True).click()
        expect(learner.get_by_text('Anotação salva no caderno.',exact=True)).to_be_visible()
        learner.reload()
        learner.locator('.st-key-sidebar_navigation a').filter(has_text='Análise').click()
        learner.get_by_role('tab',name='Caderno',exact=True).click()
        learner.get_by_role('button',name='Retomar partida anotada',exact=True).click()
        if not learner.get_by_role('textbox',name='Pontos importantes do estudo',exact=True).is_visible():
            learner.get_by_role('tab',name='Caderno',exact=True).click()
        expect(learner.get_by_role('textbox',name='Pontos importantes do estudo',exact=True)).to_have_value('Desenvolver antes de atacar.')
        expect(learner.locator('[data-testid=stException]')).to_have_count(0)
        expect(page.locator('[data-testid=stException]')).to_have_count(0)
    finally:context.close()
